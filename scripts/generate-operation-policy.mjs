import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { spawnSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "packages/contracts/src/operation-policy.v2.json");
const goPath = path.join(root, "apps/agent/internal/connector/operation_policy_generated.go");
const goOutcomePath = path.join(root, "apps/agent/internal/executor/console_outcome_generated.go");
const check = process.argv.includes("--check");

const source = JSON.parse(await readFile(sourcePath, "utf8"));
const canonical = canonicalJson(Object.fromEntries(Object.entries(source).filter(([key]) => key !== "digest")));
const digest = createHash("sha256").update(canonical).digest("hex");
const normalized = { ...source, digest };
const jsonOutput = JSON.stringify(normalized, null, 2) + "\n";
const rawGoOutput = renderGo(normalized);
const gofmt = spawnSync("gofmt", [], { input: rawGoOutput, encoding: "utf8" });
if (gofmt.status !== 0) throw new Error(`gofmt failed while generating operation policy: ${gofmt.stderr}`);
const goOutput = gofmt.stdout;
const rawGoOutcomeOutput = renderGoOutcome(normalized.console.outcome);
const goOutcomeFmt = spawnSync("gofmt", [], { input: rawGoOutcomeOutput, encoding: "utf8" });
if (goOutcomeFmt.status !== 0) throw new Error(`gofmt failed while generating console outcomes: ${goOutcomeFmt.stderr}`);
const goOutcomeOutput = goOutcomeFmt.stdout;

if (check) {
  const [currentJson, currentGo, currentGoOutcome] = await Promise.all([
    readFile(sourcePath, "utf8"),
    readFile(goPath, "utf8").catch(() => ""),
    readFile(goOutcomePath, "utf8").catch(() => ""),
  ]);
  if (currentJson !== jsonOutput || currentGo !== goOutput || currentGoOutcome !== goOutcomeOutput) {
    throw new Error("operation policy generated artifacts have drifted; run npm run policy:generate");
  }
  console.log(`operation policy ${normalized.schema_version}:${digest} is synchronized`);
} else {
  await Promise.all([
    writeFile(sourcePath, jsonOutput, "utf8"),
    writeFile(goPath, goOutput, "utf8"),
    writeFile(goOutcomePath, goOutcomeOutput, "utf8"),
  ]);
  console.log(`generated operation policy ${normalized.schema_version}:${digest}`);
}

function renderGoOutcome(outcome) {
  const failures = outcome.failure_patterns.flatMap((item) => item.patterns.map((pattern) =>
    `\t{code: ${goString(item.code)}, pattern: ${goString(pattern)}, userMessage: ${goString(item.user_message)}},`)).join("\n");
  return `// Code generated by scripts/generate-operation-policy.mjs; DO NOT EDIT.\npackage executor\n\nconst generatedConsoleOutcomeSchema = ${goString(outcome.schema_version)}\nconst generatedConsoleFrameSchema = ${goString(outcome.completeness.schema_version)}\nconst generatedConsoleMinimumVisibleRunes = ${Number(outcome.completeness.minimum_visible_runes)}\nconst generatedConsoleIncompleteMessage = ${goString(outcome.completeness.user_message)}\n\ntype generatedConsoleOutcomeFailurePattern struct { code string; pattern string; userMessage string }\n\nvar generatedConsoleOutcomeFailurePatterns = []generatedConsoleOutcomeFailurePattern{\n${failures}\n}\nvar generatedConsoleOutcomeSuccessPatterns = ${goSlice(outcome.success_patterns)}\nvar generatedConsoleOutcomeAcceptedPatterns = ${goSlice(outcome.accepted_patterns)}\n`;
}

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

function goString(value) { return JSON.stringify(String(value)); }
function goSlice(values) { return `[]string{${values.map(goString).join(", ")}}`; }
function goMap(values) {
  return `map[string]string{${Object.entries(values).map(([key, value]) => `${goString(key)}: ${goString(value)}`).join(", ")}}`;
}

function renderGo(policy) {
  const tools = Object.entries(policy.tools).map(([name, item]) =>
    `\t${goString(name)}: {action: ${goString(item.action)}, minimumRisk: ${goString(item.risk)}, requiresConfirmation: ${item.requires_confirmation}, mutates: ${item.mutates}, producerVerified: ${item.producer_verified === true}, evidenceKind: ${goString(item.evidence_kind)}, forbiddenActions: ${goSlice(item.forbidden_actions)}, verification: ${goMap(item.verification)}},`).join("\n");
  const vectors = policy.action_vectors.map((item) =>
    `\t{name: ${goString(item.name)}, tools: ${goSlice(item.tools)}, consoleCommand: ${goString(item.console_command ?? "")}, expected: ${goString(item.expected)}},`).join("\n");
  return `// Code generated by scripts/generate-operation-policy.mjs; DO NOT EDIT.\npackage connector\n\nconst generatedPolicySchema = ${goString(policy.schema_version)}\nconst generatedPolicyDigest = ${goString(policy.digest)}\nconst generatedPolicyVersion = generatedPolicySchema + ":" + generatedPolicyDigest\n\nvar generatedActionOrder = ${goSlice(policy.action_order)}\nvar generatedRiskOrder = ${goSlice(policy.risk_order)}\nvar generatedTargetKeys = ${goSlice(policy.target_keys)}\nvar generatedToolPolicies = map[string]toolPolicy{\n${tools}\n}\ntype generatedActionVector struct { name string; tools []string; consoleCommand string; expected string }\nvar generatedActionVectors = []generatedActionVector{\n${vectors}\n}\nvar generatedConsoleReadVerbs = ${goSlice(policy.console.read_verbs)}\nvar generatedConsoleReadExact = ${goSlice(policy.console.read_exact)}\nvar generatedConsoleReadPatterns = ${goSlice(policy.console.read_patterns)}\nvar generatedConsoleMediumVerbs = ${goSlice(policy.console.medium_verbs)}\nvar generatedConsoleMediumPatterns = ${goSlice(policy.console.medium_patterns)}\nvar generatedConsoleVerification = ${goMap(policy.console.verification)}\nvar generatedConsoleWriteForbiddenActions = ${goSlice(policy.console.write_forbidden_actions)}\nconst generatedConsoleEvidenceKind = ${goString(policy.console.evidence_kind)}\n`;
}
